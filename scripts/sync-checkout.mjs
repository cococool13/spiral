#!/usr/bin/env node
// Copy checkout URLs from collection/lib/checkout.ts into each app's src/lib/checkout.ts.
//
//   node scripts/sync-checkout.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
export const CANONICAL = join(ROOT, "collection/lib/checkout.ts");

export const MIRRORS = [
  "apps/wallpaper/src/lib/checkout.ts",
  "apps/clean/src/lib/checkout.ts",
  "apps/Resume/src/lib/checkout.ts",
  "apps/slim/desktop/src/lib/checkout.ts",
];

export const KEYS = ["CHECKOUT_URL", "RESEND_URL"];

function sync() {
  const canonical = readFileSync(CANONICAL, "utf8");
  const values = {};
  for (const key of KEYS) {
    const m = canonical.match(new RegExp(`export const ${key} = "([^"]+)"`));
    if (!m) {
      console.error(`sync-checkout: canonical missing ${key}`);
      process.exit(1);
    }
    values[key] = m[1];
  }

  const mirrorBody = `/** Spiral Collection checkout ($9.99 one-time) and lost-key page, served by the licensing Worker.
 *  Generated by scripts/sync-checkout.mjs — edit collection/lib/checkout.ts instead. */
export const CHECKOUT_URL = "${values.CHECKOUT_URL}";
export const RESEND_URL = "${values.RESEND_URL}";
`;

  for (const rel of MIRRORS) {
    writeFileSync(join(ROOT, rel), mirrorBody);
    console.log(`sync-checkout: wrote ${rel}`);
  }

  console.log("sync-checkout: done");
}

if (import.meta.url === pathToFileURL(resolve(process.argv[1] ?? "")).href) {
  sync();
}
